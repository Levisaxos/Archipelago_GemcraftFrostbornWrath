"""
The vanilla field-unlock tree.

Vanilla unlocks fields as a strict tree: each field's token drops from exactly
one parent's orb (on win) or wizard stash, rooted at W1. The apworld gates each
field on its vanilla parent being beaten (rules.py, "<parent> Cleared"), so
beating a field implies its whole ancestor chain, exactly like vanilla.

`depth` = number of ancestors (W1 = 0 ... A4 = 47; the main chain is 48 fields).

Data: data/vanilla_tree.json, generated by
do not commit/py-scripts/export_vanilla_tree.py from StageCollection1.as.
"""

import json
from importlib.resources import files
from typing import Dict, Optional

_TREE = json.loads(
    files(__package__).joinpath("data/vanilla_tree.json").read_text(encoding="utf-8")
)["stages"]

# {sid: vanilla parent sid} (None for the root W1)
VANILLA_PARENT: Dict[str, Optional[str]] = {sid: v["parent"] for sid, v in _TREE.items()}
# {sid: number of vanilla ancestors}
VANILLA_DEPTH: Dict[str, int] = {sid: int(v["depth"]) for sid, v in _TREE.items()}
